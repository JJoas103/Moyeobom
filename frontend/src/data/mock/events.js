const DAY = 24 * 60 * 60 * 1000

// 오늘을 기준으로 날짜를 만든다. 고정 날짜로 박아 두면 며칠만 지나도
// "종료된 행사"만 남아 화면이 텅 비어 버린다.
const today = new Date()
today.setHours(0, 0, 0, 0)

const at = (dayOffset, hour = 19, minute = 30) =>
  new Date(today.getTime() + dayOffset * DAY + (hour * 60 + minute) * 60 * 1000).toISOString()

